// Regenerates src/core/suffixes.generated.ts from the Public Suffix List.
// Usage: npm run gen:suffixes [-- path/to/public_suffix_list.dat]
import { readFileSync, writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";

const PSL_URL = "https://publicsuffix.org/list/public_suffix_list.dat";
const OUTPUT = new URL("../src/core/suffixes.generated.ts", import.meta.url);

export type SuffixList = { version: string; commit: string; suffixes: string[] };

/** Keeps the ICANN-section rules that have exactly two labels and no wildcard or exception marker. */
export function parseTwoLabelSuffixes(pslText: string): SuffixList {
  const header = (name: string) =>
    new RegExp(`^// ${name}: (.+)$`, "m").exec(pslText)?.[1]?.trim() ?? "unknown";
  const begin = pslText.indexOf("// ===BEGIN ICANN DOMAINS===");
  const end = pslText.indexOf("// ===END ICANN DOMAINS===");
  if (begin < 0 || end < begin) throw new Error("ICANN section markers not found in the list");

  const suffixes = new Set<string>();
  for (const rawLine of pslText.slice(begin, end).split("\n")) {
    const rule = rawLine.trim().split(/\s/)[0] ?? "";
    if (!rule || rule.startsWith("//") || /[*!]/.test(rule)) continue;
    const ascii = domainToASCII(rule);
    if (ascii.split(".").length === 2) suffixes.add(ascii);
  }
  return { version: header("VERSION"), commit: header("COMMIT"), suffixes: [...suffixes].sort() };
}

export function renderModule({ version, commit, suffixes }: SuffixList): string {
  return `// Generated by scripts/gen-suffixes.ts from the Public Suffix List. Do not edit.
// PSL version: ${version}
// PSL commit: ${commit}
export const twoLabelSuffixes: ReadonlySet<string> = new Set(
  "${suffixes.join(" ")}".split(" "),
);
`;
}

if (import.meta.main) {
  const localPath = process.argv[2];
  const text = localPath
    ? readFileSync(localPath, "utf8")
    : await fetch(PSL_URL).then((response) => {
        if (!response.ok) throw new Error(`Failed to download ${PSL_URL}: ${response.status}`);
        return response.text();
      });
  const list = parseTwoLabelSuffixes(text);
  writeFileSync(OUTPUT, renderModule(list));
  console.log(`Wrote ${list.suffixes.length} suffixes (PSL ${list.version})`);
}
